/** أقسام فرعية جاهزة حسب اسم القسم الرئيسي (تتعمل تلقائيًا) */
const SETS: [string[], string[]][] = [
  [['أزياء', 'ازياء', 'ملابس', 'موضة'], ['رجالي', 'حريمي', 'أطفالي', 'أحذية', 'شنط وإكسسوارات']],
  [['إلكترونيات', 'الكترونيات', 'موبايل'], ['موبايلات', 'لاب توب وكمبيوتر', 'سماعات وصوتيات', 'شاشات وتليفزيونات', 'إكسسوارات إلكترونية']],
  [['منزل', 'مطبخ'], ['أدوات مطبخ', 'أثاث', 'ديكور', 'مفروشات', 'أدوات تنظيف']],
  [['جمال', 'عناية'], ['مكياج', 'عناية بالبشرة', 'عناية بالشعر', 'عطور']],
  [['رياض'], ['ملابس رياضية', 'معدات لياقة', 'كرة قدم', 'دراجات']],
  [['كتب'], ['روايات', 'كتب تعليمية', 'كتب أطفال']],
  [['ألعاب', 'العاب'], ['ألعاب أولاد', 'ألعاب بنات', 'ألعاب تعليمية']],
  [['بقالة', 'غذاء'], ['مواد غذائية', 'مشروبات', 'حلويات وسناكس']],
];
const FALLBACK = ['رجالي', 'حريمي', 'أطفالي'];

export function defaultSubs(parentName: string): string[] {
  const n = parentName.trim();
  return SETS.find(([keys]) => keys.some((k) => n.includes(k)))?.[1] ?? FALLBACK;
}
